#!/usr/bin/env python3
"""Bundle the recordings listed in audio/manifest.json into audio/pack.js.

The game loads audio/pack.js with a <script> tag, so recorded voice and music
also play when index.html is opened straight from disk (file://), where
fetch() is blocked. Run this again after you change any recording:

    python3 tools/build-audio-pack.py
"""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
manifest = json.loads((ROOT / "audio" / "manifest.json").read_text())


def b64(rel):
    return base64.b64encode((ROOT / rel).read_bytes()).decode("ascii")


pack = {"voice": {key: b64(path) for key, path in manifest.get("voice", {}).items()}}
if manifest.get("music"):
    pack["music"] = b64(manifest["music"])

out = ROOT / "audio" / "pack.js"
out.write_text(
    "/* Generated by tools/build-audio-pack.py from audio/manifest.json. Do not edit. */\n"
    "window.LULU_AUDIO=" + json.dumps(pack, separators=(",", ":")) + ";\n"
)
print(f"{out.relative_to(ROOT)}: {len(pack['voice'])} voice clips, "
      f"music={'yes' if 'music' in pack else 'no'}, {out.stat().st_size / 1e6:.1f} MB")
